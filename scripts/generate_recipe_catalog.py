def generate():
    rows=[]
    for g,(layer,tags,specs) in enumerate(GROUPS,1):
        assert len(specs)==8
        for n,line in enumerate(specs,1):
            name,operation,observe,states,boundary=line.split('|')
            initial,final=states.split('→',1)
            rows.append(dict(id=f'{g:02}.{n:02}',name=name,layer=layer,operation=operation,observe=observe,
                initialState=initial,finalState=final,tags=layer+' '+ASSET_TAGS[g-1].split('|')[n-1],
                objectTags=OBJECT_TAGS[g-1].split('|')[n-1].split(),stateTags=STATE_TAGS[g-1].split('|')[n-1].split(),typeTags=TYPE_TAGS[g-1].split('|')[n-1].split(),boundary=boundary,
                reducedMotion=('关闭空间运动与循环，以静态轮廓和状态文字表达' if g==12 else '立即显示正确状态，保留文字、图标和必要进度，不改变操作结果'),
                duration=1.8 if g==12 or (g==4 and n==8) else (1.2 if (g,n) in ((9,7),(10,6)) else (.65 if g==11 else (.3 if (g,n)==(3,8) else .28))),interactive=True,loop=g==12))
    target=ROOT/'Assets/TweenGallery/Resources/recipe-catalog.json'
    target.write_text(json.dumps(dict(schemaVersion=2,recipes=rows),ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    return rows

if __name__=='__main__':
    rows=generate()
